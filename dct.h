#define BLOCK_SIZE 8
#ifndef M_PI
#define M_PI 3.14
#endif

typedef struct {
    double coeff[BLOCK_SIZE][BLOCK_SIZE];  // DCT коэффициенты
} Block;

typedef struct {
    int width;
    int height;
    int cbxblocks;   
    int cbyblocks;
    int xblocks;      // количество блоков по горизонтали
    int yblocks;      // количество блоков по вертикали
    Block **Yblocks;    // блоки для Y канала
    Block **Cbblocks;   // блоки для Cb
    Block **Crblocks;   // блоки для Cr
} JPEGImage;

